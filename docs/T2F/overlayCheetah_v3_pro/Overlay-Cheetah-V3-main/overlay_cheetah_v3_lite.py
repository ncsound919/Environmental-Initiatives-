    def generate(self):
        """Generate basic template - lite version"""
        name = self.name_entry.get().strip()
        if not name:
            messagebox.showwarning("Warning", "Please enter a project name.")
            return

        inputs = {
            "name": name,
            "type": self.type_var.get(),
            "features": self.features_var.get(),
        }

        stack = {"frontend": "HTML/CSS", "backend": "Python"}
        yaml = self.template.generate_yaml(inputs, stack)

        self.output_area.insert(tk.END, f"\n✓ Template generated for: {name}\n")
        self.output_area.insert(tk.END, f"Type: {inputs['type']}\n")
        self.output_area.insert(
            tk.END, f"Features: {inputs['features']}/3 (Lite limit)\n\n"
        )

        with open("generated_template_lite.yaml", "w") as f:
            f.write(yaml)

        self.output_area.insert(
            tk.END,
            "💡 Tip: Upgrade to PRO for advanced templates with 10x more customization!\n\n",
        )

        self.status_var.set("Template generated - Lite version")

    def build(self):
        """Build project - simplified in lite version"""
        if not os.path.exists("generated_template_lite.yaml"):
            messagebox.showwarning("Warning", "Please generate a template first.")
            return

        try:
            with open("generated_template_lite.yaml", "r") as f:
                yaml_content = f.read()

            self.status_var.set("Building (Basic)...")
            self.progress_var.set(50)

            def callback(result):
                if result.get("success"):
                    self.output_area.insert(
                        tk.END, f"\n✓ {result.get('message', 'Build complete!')}\n"
                    )
                    self.output_area.insert(
                        tk.END, f"Files: {', '.join(result.get('files', []))}\n\n"
                    )
                    self.progress_var.set(100)
                    self.status_var.set("Build Complete (Lite)")

                    # Remind about PRO features
                    self.output_area.insert(
                        tk.END,
                        "🌟 PRO version includes: Full build automation, testing, and deployment!\n\n",
                    )
                else:
                    messagebox.showerror(
                        "Build Error", result.get("error", "Unknown error")
                    )
                    self.status_var.set("Build Failed")

            self.builder.execute(yaml_content, callback)

        except Exception as e:
            messagebox.showerror("Error", str(e))
            self.status_var.set("Error")

