class TemplateEngine:
    """Basic template generation - limited to simple projects in lite version"""

    def generate_yaml(self, inputs, stack):
        return f"""
task_id: vibe_build_{inputs["name"]}
description: Generated by OverlayCheetah V3 Lite (Free Version)
files:
  - template: main_app.py.j2
    output: app.py
    context:
      app_name: "{inputs["name"]}"
      features: {inputs.get("features", 3)}
      stack: {stack}
note: "Upgrade to PRO for advanced templates and customization!"
"""


class BuildExecutor:
    """Basic build executor - limited output in lite version"""

    def execute(self, yaml_content, callback=None):
        try:
            with open("generated_template_lite.yaml", "w") as f:
                f.write(yaml_content)
            result = {
                "success": True,
                "files": ["app.py"],
                "message": "✓ Basic template generated! Upgrade to PRO for full build automation.",
            }
            if callback:
                callback(result)
        except Exception as e:
            if callback:
                callback({"success": False, "error": str(e)})


class OnboardingWizard:
    """Simple onboarding for first-time users"""

    def __init__(self, root, callback):
        self.root = root
        self.callback = callback
        self.step = 0
        self.data = {}
        self.dialog = tk.Toplevel(root)
        self.dialog.title("Welcome to OverlayCheetah V3 Lite!")
        self.dialog.geometry("600x450")
        self.setup_steps()

    def setup_steps(self):
        self.steps = [
            self.step_welcome,
            self.step_preset,
            self.step_details,
            self.step_upgrade_info,
        ]
        self.next_step()

    def next_step(self):
        if self.step < len(self.steps):
            for widget in self.dialog.winfo_children():
                widget.destroy()
            self.steps[self.step]()
            self.step += 1
        else:
            self.dialog.destroy()
            self.callback(self.data)

    def step_welcome(self):
        ttk.Label(
            self.dialog,
            text="Welcome to OverlayCheetah V3 Lite!",
            font=("Arial", 16, "bold"),
        ).pack(pady=20)
        ttk.Label(
            self.dialog,
            text="🎉 Free version - Build simple SaaS projects quickly!",
            font=("Arial", 12),
        ).pack(pady=10)
        ttk.Label(
            self.dialog,
            text="Let's create your first project together.",
            font=("Arial", 10),
        ).pack(pady=5)
        ttk.Button(self.dialog, text="Get Started", command=self.next_step).pack(
            pady=20
        )

    def step_preset(self):
        ttk.Label(
            self.dialog, text="Choose a starter template:", font=("Arial", 12)
        ).pack(pady=10)
        self.preset_var = tk.StringVar(value="Simple Blog")

        presets = [
            ("Simple Blog", "Basic blog with posts"),
            ("Task List", "Simple todo app"),
            ("Landing Page", "Single page website"),
        ]

        for preset_name, description in presets:
            frame = ttk.Frame(self.dialog)
            frame.pack(pady=5, fill="x", padx=20)
            ttk.Radiobutton(
                frame, text=preset_name, variable=self.preset_var, value=preset_name
            ).pack(side="left")
            ttk.Label(frame, text=f"- {description}", foreground="gray").pack(
                side="left"
            )

        ttk.Label(
            self.dialog,
            text="💡 PRO version includes 15+ advanced templates!",
            foreground="blue",
            font=("Arial", 9, "italic"),
        ).pack(pady=10)

        ttk.Button(self.dialog, text="Next", command=lambda: self.set_preset()).pack(
            pady=20
        )

    def set_preset(self):
        self.data["preset"] = self.preset_var.get()
        self.next_step()

    def step_details(self):
        ttk.Label(self.dialog, text="Project details:", font=("Arial", 12)).pack(
            pady=10
        )

        ttk.Label(self.dialog, text="Project Name:").pack()
        self.name_entry = ttk.Entry(self.dialog, width=40)
        self.name_entry.pack(pady=5)
        self.name_entry.insert(0, "MyFirstProject")

        ttk.Button(self.dialog, text="Next", command=lambda: self.set_details()).pack(
            pady=20
        )

    def set_details(self):
        self.data["name"] = self.name_entry.get()
        self.data["type"] = "Simple SaaS App"
        self.next_step()

    def step_upgrade_info(self):
        ttk.Label(
            self.dialog, text="🚀 Ready to build!", font=("Arial", 14, "bold")
        ).pack(pady=20)

        # Show lite version limitations
